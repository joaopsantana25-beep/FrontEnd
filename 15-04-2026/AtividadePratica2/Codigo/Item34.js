/*
34.Manipulando Arrays com shift() e unshift()
Objetivo: Crie um array de frutas e utilize shift() para remover o
primeiro item e unshift() para adicionar um novo item no início.
*/

let frutas = ["Banana","Maçã","Pera"]

console.log(frutas)

frutas.shift()

console.log(frutas)

frutas.unshift("Uvas")

console.log(frutas)