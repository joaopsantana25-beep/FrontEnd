/*
1.Função Somar
Descrição: Uma função simples que recebe dois números inteiros e retorna
a soma deles. Conceitos utilizados:
• Função: Definimos uma função utilizando function , que é uma unidade
de código reutilizável.
• Parâmetros: x e y são os valores fornecidos à função para que ela realize o
cálculo.
• Operação aritmética: A soma é realizada com o operador +.
• Retorno: A função usa return para enviar o resultado da operação.
*/

function somar(x,y){
    return x+y
}



console.log(somar(5,6))